import '../../core/enums/risk_level.dart';
import '../../core/enums/submission_status.dart';
import '../../domain/entities/utilization_submission.dart';

class UtilizationSubmissionModel extends UtilizationSubmissionEntity {
  const UtilizationSubmissionModel({
    required super.submissionId,
    required super.loanId,
    required super.beneficiaryId,
    required super.amountSpent,
    required super.description,
    required super.photoUrls,
    required super.videoUrls,
    required super.documentUrls,
    required super.latitude,
    required super.longitude,
    required super.locationAccuracy,
    super.altitude,
    super.registeredVillage,
    super.gpsSource,
    super.isMocked,
    super.capturedOffline,
    required super.capturedAt,
    required super.uploadedAt,
    required super.status,
    super.aiScore,
    required super.riskLevel,
    super.reviewedBy,
    super.reviewedAt,
    super.rejectionReason,
    super.deviceInfo,
    required super.createdAt,
    required super.updatedAt,
  });

  factory UtilizationSubmissionModel.fromMap(Map<String, dynamic> map, String id) {
    return UtilizationSubmissionModel(
      submissionId: id,
      loanId: map['loanId'] ?? '',
      beneficiaryId: map['beneficiaryId'] ?? '',
      amountSpent: (map['amountSpent'] ?? 0.0).toDouble(),
      description: map['description'] ?? '',
      photoUrls: List<String>.from(map['photoUrls'] ?? []),
      videoUrls: List<String>.from(map['videoUrls'] ?? []),
      documentUrls: List<String>.from(map['documentUrls'] ?? []),
      latitude: (map['latitude'] ?? 0.0).toDouble(),
      longitude: (map['longitude'] ?? 0.0).toDouble(),
      locationAccuracy: (map['locationAccuracy'] ?? map['accuracy'] ?? 0.0).toDouble(),
      altitude: (map['altitude'] ?? 0.0).toDouble(),
      registeredVillage: map['registeredVillage'] ?? map['village'] ?? 'Ojewadi',
      gpsSource: map['gpsSource'] ?? 'GNSS',
      isMocked: map['isMocked'] ?? false,
      capturedOffline: map['capturedOffline'] ?? false,
      capturedAt: map['capturedAt'] != null ? DateTime.parse(map['capturedAt']) : DateTime.now(),
      uploadedAt: map['uploadedAt'] != null ? DateTime.parse(map['uploadedAt']) : DateTime.now(),
      status: SubmissionStatus.fromString(map['status']),
      aiScore: map['aiScore'] != null ? (map['aiScore'] as num).toDouble() : null,
      riskLevel: RiskLevel.fromString(map['riskLevel']),
      reviewedBy: map['reviewedBy'],
      reviewedAt: map['reviewedAt'] != null ? DateTime.parse(map['reviewedAt']) : null,
      rejectionReason: map['rejectionReason'],
      deviceInfo: map['deviceInfo'] ?? 'Android 14 (Mobile Geotagged)',
      createdAt: map['createdAt'] != null ? DateTime.parse(map['createdAt']) : DateTime.now(),
      updatedAt: map['updatedAt'] != null ? DateTime.parse(map['updatedAt']) : DateTime.now(),
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'submissionId': submissionId,
      'loanId': loanId,
      'beneficiaryId': beneficiaryId,
      'fileUrl': fileUrl,
      'fileType': fileType,
      'amountSpent': amountSpent,
      'description': description,
      'photoUrls': photoUrls,
      'videoUrls': videoUrls,
      'documentUrls': documentUrls,
      'latitude': latitude,
      'longitude': longitude,
      'locationAccuracy': locationAccuracy,
      'accuracy': locationAccuracy,
      'altitude': altitude,
      'registeredVillage': registeredVillage,
      'gpsSource': gpsSource,
      'isMocked': isMocked,
      'capturedOffline': capturedOffline,
      'submittedAt': submittedAt.toIso8601String(),
      'capturedAt': capturedAt.toIso8601String(),
      'uploadedAt': uploadedAt.toIso8601String(),
      'status': status.value,
      'aiStatus': aiStatus,
      'aiConfidence': aiConfidence,
      'officerStatus': officerStatus,
      'officerRemarks': officerRemarks,
      'aiScore': aiScore,
      'riskLevel': riskLevel.value,
      'reviewedBy': reviewedBy,
      'reviewedAt': reviewedAt?.toIso8601String(),
      'rejectionReason': rejectionReason,
      'deviceInfo': deviceInfo ?? 'Android 14 (Mobile Geotagged)',
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt.toIso8601String(),
    };
  }
}
